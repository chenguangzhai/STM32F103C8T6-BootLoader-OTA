/**
  * W25Q64 上电自检模块
  *
  * 目的：设备上电后一跑就知道 Flash 这一路到底是通的、坏的、还是接线错了。
  * 把「读 ID / 擦 / 写 / 读回比对」串成一次检查，结果由串口打印，
  * 不用示波器、不用打断点就能定位问题出在哪一步。
  *
  * 为什么只测最后一个扇区：W25Q64 共 8 MB，前部通常留给 OTA 固件镜像。
  * 自检固定擦 0x7FF000（末 4 KB 扇区），避免把待升级的固件擦掉。
  * 若你的固件方案把末尾也用作分区，改 w25q_test.c 里的 TEST_SECTOR_ADDR 即可。
  */
#ifndef __W25Q_TEST_H
#define __W25Q_TEST_H

#include <stdint.h>

/**
  * @brief  执行一次 W25Q64 自检：初始化 -> 读 ID -> 擦扇区 -> 写入 -> 读回比对
  * @retval 0 全部通过；非 0 为失败步骤编号（见串口输出）
  * @note   内部会调用 W25q_Init() 绑定 SPI1/PB0，调用方不必再初始化一次。
  *         本函数阻塞（擦除期间最长约 400 ms），只在启动阶段调用，别放主循环。
  *         结果通过 Uart_Printf(UART_LOG, ...) 打印，波特率与业务口一致。
  */
uint8_t W25q_Test(void);

#endif /* __W25Q_TEST_H */
